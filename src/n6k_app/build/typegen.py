"""Generate `<appDir>/n6k.gen.ts`.

A TypeScript augmentation of `@n6k.io/ui`'s `N6kRegister` seam, so chart/stat
bindings (`data=`, `x=`, `y=`, `value=`, `hue=`, …) type-check against this
app's real tables + columns. Regenerated on every `n6k build`; gitignored.

Column types are emitted only where they're statically known — a source table
annotated with `Table[Schema]` / an explicit `schema=`. Views and un-annotated
tables get a permissive column map (the relation *name* is still checked; its
columns fall back to `string`), because discovering their columns would mean
running the user's loaders or a live DuckDB at build time.
"""

import logging
import re
from pathlib import Path

import pyarrow as pa
from fastapi import FastAPI

_log = logging.getLogger(__name__)

GEN_FILENAME = "n6k.gen.ts"

_IDENT_RE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")

_HEADER = """\
// AUTO-GENERATED by `n6k build` — do not edit. Regenerated on every build.
// Registers this app's tables + columns with @n6k.io/ui so chart/stat bindings
// (data=, x=, y=, value=, hue=, …) type-check against the real schema.
import "@n6k.io/ui/components";

declare module "@n6k.io/ui/components" {
  interface N6kRegister {
    tables: {
"""

_FOOTER = """\
    };
  }
}
"""


def _ts_type(arrow_type: pa.DataType) -> str:
    if pa.types.is_boolean(arrow_type):
        return "boolean"
    if pa.types.is_integer(arrow_type) or pa.types.is_floating(arrow_type) or pa.types.is_decimal(arrow_type):
        return "number"
    if pa.types.is_string(arrow_type) or pa.types.is_large_string(arrow_type):
        return "string"
    if pa.types.is_temporal(arrow_type):  # date/time/timestamp serialize as strings
        return "string"
    return "unknown"


def _quote_key(name: str) -> str:
    if _IDENT_RE.match(name):
        return name
    return '"' + name.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _columns_ts(schema: pa.Schema | None) -> str:
    """A TS object type for a relation's columns, or a permissive map when the
    columns aren't statically known (so `ColumnOf<T>` falls back to `string`)."""
    if schema is None or len(schema) == 0:
        return "Record<string, unknown>"
    parts = [f"{_quote_key(f.name)}: {_ts_type(f.type)}" for f in schema]
    return "{ " + "; ".join(parts) + " }"


def _relation_key(alias: str, schema: str, name: str) -> str:
    # `main` is implicit in bindings (`page.orders`); other schemas are explicit
    # (`page.pg.orders`), matching the 3-part namespace the frontend resolves.
    if schema and schema != "main":
        return f"{alias}.{schema}.{name}"
    return f"{alias}.{name}"


def generate_types(project_dir: Path, app: FastAPI | None, app_dir: str) -> Path | None:
    """Write `<app_dir>/n6k.gen.ts` from the discovered app. Returns the path,
    or None if there's nothing to generate."""
    from n6k_app.database import page_databases_by_slug

    by_slug = page_databases_by_slug(app, Path(app_dir).name) if app is not None else {}
    if not by_slug:
        return None

    # A database attaches under the variable name each page binds it to.
    entries: dict[str, str] = {}
    for dbs in by_slug.values():
        for alias, db in dbs.items():
            reg = db.table_registry
            for name, spec in reg.table_specs().items():
                entries[_relation_key(alias, spec.schema, name)] = _columns_ts(spec.arrow_schema)
            for name, vspec in reg.view_specs().items():
                entries.setdefault(_relation_key(alias, vspec.schema, name), _columns_ts(None))

    body = "".join(f'      {_quote_key_or_str(key)}: {cols};\n' for key, cols in sorted(entries.items()))
    content = _HEADER + body + _FOOTER

    out = project_dir / app_dir / GEN_FILENAME
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content)
    _log.info("Wrote %s (%d relations)", out, len(entries))
    return out


def _quote_key_or_str(key: str) -> str:
    # relation keys contain dots, so always quote them
    return '"' + key.replace("\\", "\\\\").replace('"', '\\"') + '"'
